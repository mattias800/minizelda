export const GLYPH_W = 5;
export const GLYPH_H = 7;
/** Horizontal distance between characters. */
export const CHAR_ADVANCE = 7;
export const LINE_HEIGHT = 10;

export function hasGlyph(ch: string): boolean {
  return ch.toUpperCase() in GLYPHS;
}

export function glyphRows(ch: string): string[] | undefined {
  return GLYPHS[ch.toUpperCase()];
}

export function textWidth(text: string): number {
  return text.length === 0 ? 0 : text.length * CHAR_ADVANCE - (CHAR_ADVANCE - GLYPH_W);
}

/** Splits text into lines no longer than `maxChars`, breaking on spaces. Explicit "\n" is honored. */
export function wrapText(text: string, maxChars: number): string[] {
  const lines: string[] = [];
  for (const paragraph of text.split("\n")) {
    let line = "";
    for (const word of paragraph.split(" ")) {
      const candidate = line ? `${line} ${word}` : word;
      if (candidate.length > maxChars && line) {
        lines.push(line);
        line = word;
      } else {
        line = candidate;
      }
    }
    lines.push(line);
  }
  return lines;
}

